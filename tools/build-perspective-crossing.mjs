#!/usr/bin/env node
/**
 * Builds perspective-crossing.html (the gallery page) from the perspective-illusion
 * skill's night template, so the page never drifts from the skill.
 *
 *   node tools/build-perspective-crossing.mjs          # write the page
 *   node tools/build-perspective-crossing.mjs --check  # exit 1 if the page is stale
 *
 * GitHub Pages does not serve dot-folders (.claude/), so the page must stand alone:
 *   - three.js comes from a pinned CDN build instead of ./node_modules,
 *   - lib/camera.js is inlined into the scene module,
 *   - a player (play/pause, scrub, shot captions, quality) is added on top of the
 *     template's page contract: window.render(ms) / window.renderMany(list).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SKILL = join(ROOT, '.claude', 'skills', 'perspective-illusion', 'templates');
export const OUT = join(ROOT, 'perspective-crossing.html');
export const THREE_VERSION = '0.170.0';
const CDN = `https://cdn.jsdelivr.net/npm/three@${THREE_VERSION}`;

/** Shot captions, keyed by loop time (s). They follow the template's KEYS. */
const CAPTIONS = [
  [0.0, 'Flat', 'A 2° lens from 860 m away squashes the crossing into one flat drawing.'],
  [1.3, 'Dolly zoom', 'The lens widens while the camera moves in: same subject size, depth opens up.'],
  [3.7, 'Corner view, telephoto', 'Swung round and raised, it still reads like a flat axonometric drawing…'],
  [5.6, 'Corner view, wide', '…until the lens widens and it turns 3D.'],
  [7.4, 'Flat again', 'While the view is flat, the red umbrellas slide in depth. Nobody can tell.'],
  [10.2, 'High view', 'The row was a diagonal all along.'],
  [11.0, 'Other corner', 'Telephoto first, then wide: the scramble opens up from the other side.'],
  [12.35, "Worm's eye", 'Knee height in the rain, horizon pushed low.'],
  [13.25, 'Flat', 'Back where it started, and the umbrellas slide home: the loop closes.'],
];

/** Inline camera.js as plain declarations (its exports become module-local). */
function inlineCamera(camera) {
  const body = camera.replace(/^export\s+/gm, '');
  return `/* ---- inlined from templates/lib/camera.js ---- */\n${body}\n/* ---- end camera.js ---- */\n`;
}

export function build() {
  let html = readFileSync(join(SKILL, 'scramble_night.html'), 'utf8');
  const camera = readFileSync(join(SKILL, 'lib', 'camera.js'), 'utf8');

  html = html.replace(/<title>[^<]*<\/title>/, '<title>Perspective Crossing</title>');
  html = html.replace(/<script type="importmap">[\s\S]*?<\/script>/, `<script type="importmap">
{ "imports": {
    "three": "${CDN}/build/three.module.js",
    "three/addons/": "${CDN}/examples/jsm/"
} }
</script>`);
  if (html.includes('./node_modules/')) throw new Error('node_modules reference survived');

  const importRe = /import \{[^}]*\} from '\.\/lib\/camera\.js';\n/;
  if (!importRe.test(html)) throw new Error('template changed: camera.js import not found');
  html = html.replace(importRe, () => inlineCamera(camera));

  html = html.replace('<!doctype html>', `<!doctype html>
<!-- GENERATED by tools/build-perspective-crossing.mjs from
     .claude/skills/perspective-illusion/templates/scramble_night.html. Do not edit by hand:
     change the template, then run  node tools/build-perspective-crossing.mjs  -->`);

  const head = `
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="description" content="A rainy night scramble crossing that looks flat, then opens into 3D: an interactive perspective illusion.">
<script>
  /* Pick a render size before the scene module reads ?scale: phones and small screens
     get a lighter frame. The quality menu reloads with an explicit ?scale. */
  (function () {
    var q = new URLSearchParams(location.search);
    if (!q.has('scale')) {
      var small = Math.min(screen.width, screen.height) < 700;
      q.set('scale', small ? '0.4' : '0.6');
      history.replaceState(null, '', location.pathname + '?' + q.toString() + location.hash);
    }
  })();
</script>
<style>
  :root { --bar: rgba(10, 11, 22, 0.78); --ink: #f2eef8; --muted: #a9a6bd; --accent: #ff4f9a; }
  html, body { height: 100%; overflow: hidden; }
  body { display: grid; place-items: center; font-family: "Inter", system-ui, sans-serif; color: var(--ink); }
  #frame { width: 100vw !important; height: auto !important; max-height: 100vh; aspect-ratio: 16 / 9; object-fit: contain; }
  .pc-caption { position: fixed; top: 16px; left: 16px; right: 16px; max-width: 34rem; padding: 10px 14px;
    background: var(--bar); border-radius: 10px; backdrop-filter: blur(6px); line-height: 1.35; transition: opacity .3s; }
  .pc-caption b { display: block; font-size: 12px; letter-spacing: .12em; text-transform: uppercase; color: var(--accent); }
  .pc-caption span { font-size: 15px; }
  .pc-caption.hidden { opacity: 0; pointer-events: none; }
  .pc-bar { position: fixed; left: 16px; right: 16px; bottom: 16px; display: flex; gap: 10px; align-items: center;
    padding: 8px 12px; background: var(--bar); border-radius: 12px; backdrop-filter: blur(6px); flex-wrap: wrap; }
  .pc-bar button, .pc-bar select, .pc-bar a { font: inherit; font-size: 14px; color: var(--ink); background: rgba(255,255,255,.08);
    border: 1px solid rgba(255,255,255,.18); border-radius: 8px; padding: 6px 10px; cursor: pointer; text-decoration: none; min-height: 34px; }
  .pc-bar button:focus-visible, .pc-bar select:focus-visible, .pc-bar a:focus-visible, .pc-bar input:focus-visible { outline: 2px solid var(--accent); outline-offset: 2px; }
  .pc-bar input[type=range] { flex: 1 1 160px; accent-color: var(--accent); min-width: 120px; }
  .pc-time { font-variant-numeric: tabular-nums; color: var(--muted); font-size: 13px; min-width: 3.6em; text-align: right; }
  .pc-loading { position: fixed; inset: 0; display: grid; place-items: center; color: var(--muted); font-size: 15px; pointer-events: none; }
  @media (max-width: 520px) { .pc-caption span { font-size: 13px; } .pc-bar { gap: 6px; } }
</style>
`;
  html = html.replace('</head>', `${head}</head>`);

  const player = `
<div class="pc-loading" id="pcLoading">Building the crossing…</div>
<div class="pc-caption" id="pcCaption" aria-live="polite"><b id="pcShot"></b><span id="pcText"></span></div>
<div class="pc-bar" role="group" aria-label="Player">
  <a href="index.html" aria-label="Back to the arcade">← Arcade</a>
  <button id="pcPlay" type="button" aria-label="Pause">❚❚</button>
  <input id="pcScrub" type="range" min="0" max="1000" value="0" aria-label="Position in the loop">
  <span class="pc-time" id="pcTime">0.0 s</span>
  <select id="pcSpeed" aria-label="Speed"><option value="0.25">¼×</option><option value="0.5">½×</option><option value="1" selected>1×</option></select>
  <select id="pcQuality" aria-label="Quality"><option value="0.4">Light</option><option value="0.6">Medium</option><option value="1">Full</option></select>
  <button id="pcCaptions" type="button" aria-pressed="true">Captions</button>
</div>
<script type="module">
  /* Player: drives the scene's page contract. Space plays/pauses, ←/→ step, C toggles captions. */
  const CAPTIONS = ${JSON.stringify(CAPTIONS)};
  const $ = (id) => document.getElementById(id);
  const q = new URLSearchParams(location.search);
  $('pcQuality').value = ['0.4', '0.6', '1'].includes(q.get('scale')) ? q.get('scale') : '0.6';
  let t = 0, speed = 1, last = null, sharp = false, scrubbing = false;
  let playing = !matchMedia('(prefers-reduced-motion: reduce)').matches;

  function captionAt(sec) { let c = CAPTIONS[0]; for (const k of CAPTIONS) if (sec >= k[0]) c = k; return c; }
  function ui() {
    const loop = window.LOOP_MS;
    $('pcScrub').value = String(Math.round((t / loop) * 1000));
    $('pcTime').textContent = (t / 1000).toFixed(1) + ' s';
    const [, shot, text] = captionAt(t / 1000);
    if ($('pcShot').textContent !== shot) { $('pcShot').textContent = shot; $('pcText').textContent = text; }
    $('pcPlay').textContent = playing ? '❚❚' : '▶';
    $('pcPlay').setAttribute('aria-label', playing ? 'Pause' : 'Play');
  }
  /* Paused: replace the single-sample frame with an 8-sample anti-aliased still. */
  function sharpen() {
    const list = [];
    for (let i = 0; i < 8; i++) list.push([t, ((i * 0.618) % 1) - 0.5, ((i * 0.382 + 0.25) % 1) - 0.5]);
    window.renderMany(list); sharp = true;
  }
  function tick(now) {
    requestAnimationFrame(tick);
    if (!window.READY) return;
    if ($('pcLoading')) $('pcLoading').remove();
    const dt = last === null ? 0 : Math.min(100, now - last);
    last = now;
    if (playing && !scrubbing) {
      t = (t + dt * speed) % window.LOOP_MS;
      window.render(t); sharp = false; ui();
    } else if (!sharp && !scrubbing) { sharpen(); ui(); }
  }
  requestAnimationFrame(tick);

  const toggle = () => { playing = !playing; sharp = false; ui(); };
  const step = (ms) => { playing = false; t = (t + ms + window.LOOP_MS) % window.LOOP_MS; window.render(t); sharp = false; ui(); };
  $('pcPlay').addEventListener('click', toggle);
  $('pcScrub').addEventListener('input', (e) => {
    if (!window.READY) return;
    scrubbing = true; t = (Number(e.target.value) / 1000) * window.LOOP_MS; window.render(t); sharp = false; ui();
  });
  $('pcScrub').addEventListener('change', () => { scrubbing = false; last = null; });
  $('pcSpeed').addEventListener('change', (e) => { speed = Number(e.target.value); });
  $('pcQuality').addEventListener('change', (e) => { q.set('scale', e.target.value); location.search = q.toString(); });
  $('pcCaptions').addEventListener('click', (e) => {
    const on = $('pcCaption').classList.toggle('hidden') === false;
    e.currentTarget.setAttribute('aria-pressed', String(on));
  });
  addEventListener('keydown', (e) => {
    if (e.target instanceof HTMLInputElement || e.target instanceof HTMLSelectElement) return;
    if (e.code === 'Space') { e.preventDefault(); toggle(); }
    else if (e.key === 'ArrowRight') step(500);
    else if (e.key === 'ArrowLeft') step(-500);
    else if (e.key === 'c' || e.key === 'C') $('pcCaptions').click();
  });
</script>
`;
  html = html.replace(/<\/body>\s*<\/html>\s*$/, `${player}</body>\n</html>\n`);
  if (!html.includes('id="pcPlay"')) throw new Error('template changed: </body> not found');
  return html;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const html = build();
  if (process.argv.includes('--check')) {
    const current = readFileSync(OUT, 'utf8');
    if (current !== html) {
      console.error('perspective-crossing.html is stale: run node tools/build-perspective-crossing.mjs');
      process.exit(1);
    }
    console.log('perspective-crossing.html is up to date');
  } else {
    writeFileSync(OUT, html);
    console.log(`wrote ${OUT} (${(html.length / 1024).toFixed(0)} KiB)`);
  }
}
